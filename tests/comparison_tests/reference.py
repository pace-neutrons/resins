"""Loading of committed reference data and construction of parametrized test cases.

The reference files in ``tests/reference_data`` are generated by ``dev/reference`` (see its
README). They define the test cases: tests are parametrized from the case table in each file,
so that the same cases are collected on every machine.
"""

from __future__ import annotations

import json
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from functools import cache
from pathlib import Path

import numpy as np
import pytest

REFERENCE_DIR = Path(__file__).resolve().parents[1] / "reference_data"

VALUE, NO_TRANSMISSION, REJECTED_EI, REJECTED_FREQUENCY = range(4)
EVALUATED = (VALUE, NO_TRANSMISSION)


@dataclass(frozen=True)
class ReferenceFile:
    """One loaded reference file."""

    stem: str  # e.g. "pychop/MARI_PyChop_fit_v1"
    arrays: dict[str, np.ndarray] = field(repr=False)
    metadata: dict = field(repr=False)

    @property
    def cases(self) -> np.ndarray:
        return self.arrays["cases"]

    def __getitem__(self, name: str) -> np.ndarray:
        return self.arrays[name]

    @property
    def instrument(self) -> str:
        return self.metadata["instrument"]

    @property
    def model_version(self) -> str:
        return self.metadata["model_version"]

    @property
    def frequency_settings(self) -> list[str]:
        """Setting names of the chopper frequencies, in column order (PyChop files)."""
        return self.metadata["frequency_settings"]

    def frequencies(self, case_index: int) -> list[int]:
        """The chopper frequencies of case ``case_index``: ``f0``, ``f1`` where used (0 marks unused)."""
        case = self.cases[case_index]
        return [
            int(case[name])
            for name in ("f0", "f1")
            if name in case.dtype.names and case[name]
        ]

    def frequency_kwargs(self, case_index: int) -> dict[str, int]:
        return dict(zip(self.frequency_settings, self.frequencies(case_index)))


@cache
def load(stem: str) -> ReferenceFile:
    """Load ``reference_data/<stem>.npz`` (cached for the session)."""
    with np.load(REFERENCE_DIR / f"{stem}.npz", allow_pickle=False) as data:
        arrays = {k: data[k] for k in data.files if k != "metadata"}
        metadata = json.loads(str(data["metadata"]))
    return ReferenceFile(stem, arrays, metadata)


def reference_files_in(directory: str) -> list[str]:
    """All reference files in a sub-directory, sorted."""
    return sorted(
        f"{directory}/{path.stem}" for path in (REFERENCE_DIR / directory).glob("*.npz")
    )


def pychop_reference_files() -> list[str]:
    return reference_files_in("pychop")


# ----------------------------------------------------------------------------------------------
# Known discrepancies
# ----------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class KnownDiscrepancy:
    """A known disagreement between resins and the reference implementation.

    The affected cases are marked as strict expected failures, so a fix (or an unrelated
    change) that makes them pass is reported and the entry gets removed.

    Attributes
    ----------
    file
        The reference file stem.
    scopes
        The kinds of test the discrepancy shows up in (``"resolution"``,
        ``"abins"``); other tests of the same cases are unaffected.
    applies
        Predicate on ``(reference_file, case_index)`` selecting the affected cases.
    reason
        Why they differ.
    """

    file: str
    scopes: frozenset[str]
    applies: Callable[[ReferenceFile, int], bool]
    reason: str


# With pslit 1.5 mm (instead of Mantid's 1.0 mm) resins transmits at these points where Mantid
# does not; they sit just beyond Mantid's transmission edge, and are part of the same
# discrepancy. Other no-transmission cases of the configuration agree. If the reference data is
# regenerated with different sampling, re-derive this set by running the tests with
# RESINS_IGNORE_KNOWN_DISCREPANCIES=1 and listing the failing test_no_transmission cases.
_ARCS_SMI_700_NO_TRANSMISSION_POINTS = frozenset(
    {
        (20.0, 240.0),
        (22.545, 240.0),
        (35.227, 300.0),
        (47.43, 360.0),
        (47.43, 420.0),
        (50.727, 360.0),
        (69.044, 420.0),
        (90.18, 480.0),
        (112.5, 540.0),
        (112.5, 600.0),
        (114.13, 540.0),
        (140.91, 600.0),
    }
)


def _arcs_700_1_5_smi(ref: ReferenceFile, case_index: int) -> bool:
    """Value cases of ARCS-700-1.5-SMI, and the no-transmission cases that resins transmits."""
    case = ref.cases[case_index]
    if str(case["configuration"]) != "ARCS-700-1.5-SMI":
        return False
    if case["outcome"] == VALUE:
        return True
    return (
        case["outcome"] == NO_TRANSMISSION
        and (float(case["e_init"]), float(case["f0"]))
        in _ARCS_SMI_700_NO_TRANSMISSION_POINTS
    )


def _lagrange_cu220_window(ref: ReferenceFile, case_index: int) -> bool:
    case = ref.cases[case_index]
    return (
        str(case["configuration"]) == "Cu(220)"
        and 25.0 <= case["energy_transfer"] < 34.5
    )


KNOWN_DISCREPANCIES = (
    KnownDiscrepancy(
        file="pychop/ARCS_PyChop_fit_v2",
        scopes=frozenset({"resolution"}),
        applies=_arcs_700_1_5_smi,
        reason="Mantid has pslit: 1.0 mm for ARCS-700-1.5-SMI while resins has 1.5 mm "
        "(to be raised with Mantid/SNS)",
    ),
    KnownDiscrepancy(
        file="abins/lagrange",
        scopes=frozenset({"abins"}),
        applies=_lagrange_cu220_window,
        reason="AbINS_v1 Cu(220) differs from Abins from 25 meV up to the point where the "
        "polynomial reaches the 0.8 meV floor (about 34.5 meV); to be resolved by "
        "implementing AbINS_v2 to match Mantid 6.15+",
    ),
)


def known_discrepancy_marks(
    ref: ReferenceFile, case_index: int, scope: str
) -> list[pytest.MarkDecorator]:
    """Strict xfail marks for case ``case_index`` of ``ref`` in tests of kind ``scope``."""
    return [
        pytest.mark.xfail(strict=True, reason=discrepancy.reason)
        for discrepancy in KNOWN_DISCREPANCIES
        if discrepancy.file == ref.stem
        and scope in discrepancy.scopes
        and discrepancy.applies(ref, case_index)
    ]


# ----------------------------------------------------------------------------------------------
# Test ids and params
# ----------------------------------------------------------------------------------------------

_format_number = "{:.6g}".format


def case_id(ref: ReferenceFile, case_index: int) -> str:
    """Readable id: instrument, model version, configuration and parameter values."""
    case = ref.cases[case_index]
    names = case.dtype.names
    if "instrument" in names:
        parts = [str(case["instrument"])]
    elif "instrument" in ref.metadata:
        parts = [f"{ref.instrument}-{ref.model_version}"]
    else:
        parts = [Path(ref.stem).name]
    if "configuration" in names and str(case["configuration"]):
        parts.append(str(case["configuration"]))
    if "e_init" in names:
        parts.append(f"ei={_format_number(case['e_init'])}")
    if "energy_transfer" in names:
        parts.append(f"e={_format_number(case['energy_transfer'])}")
    frequencies = ref.frequencies(case_index)
    if frequencies:
        parts.append("f=" + ",".join(_format_number(freq) for freq in frequencies))
    return "-".join(parts)


def case_params(
    reference_files: str | Sequence[str],
    scope: str,
    outcomes: tuple[int, ...] | None = None,
) -> list:
    """``pytest.param((file, index))`` for each case, with known-discrepancy marks.

    Parameters
    ----------
    reference_files
        Reference file name(s) or path(s) relative to ``reference_data``, without
        the ``.npz`` extension (e.g. ``"pychop/MARI_PyChop_fit_v1"`` or
        ``["abins/pychop", "abins/panther"]``).
    scope
        Kind of test, used to select known discrepancies (``"resolution"`` or ``"abins"``).
    outcomes
        Outcome codes to include; all by default.
    """
    if isinstance(reference_files, str):
        file_list = [reference_files]
    else:
        file_list = list(reference_files)

    params = []
    for file in file_list:
        ref = load(file)
        for case_index, case in enumerate(ref.cases):
            if outcomes is not None and case["outcome"] not in outcomes:
                continue
            params.append(
                pytest.param(
                    (file, case_index),
                    id=case_id(ref, case_index),
                    marks=known_discrepancy_marks(ref, case_index, scope),
                )
            )
    return params


def resolve(param: tuple[str, int]) -> tuple[ReferenceFile, int]:
    file, case_index = param
    return load(file), case_index
