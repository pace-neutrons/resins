# Test ids and params
# ----------------------------------------------------------------------------------------------


def _format_number(value: float) -> str:
    return f"{value:.6g}"


def case_id(ref: ReferenceFile, i: int) -> str:
    """Readable id: instrument, model version, configuration and parameter values."""
    case = ref.cases[i]
    names = case.dtype.names
    if "instrument" in names:
        parts = [str(case["instrument"])]
    elif "instrument" in ref.metadata:
        parts = [f"{ref.instrument}-{ref.model_version}"]
    else:
        parts = [Path(ref.stem).name]
    if "configuration" in names and str(case["configuration"]):
        parts.append(str(case["configuration"]))
    if "e_init" in names:
        parts.append(f"ei={_format_number(case['e_init'])}")
    if "energy_transfer" in names:
        parts.append(f"e={_format_number(case['energy_transfer'])}")
    frequencies = ref.frequencies(i)
    if frequencies:
        parts.append("f=" + ",".join(_format_number(f) for f in frequencies))
    return "-".join(parts)


def case_params(
    stem_list: list[str],
    scope: str,
    outcomes: tuple[int, ...] | None = None,
) -> list:
    """``pytest.param((stem, index))`` for each case, with known-discrepancy marks.

    Parameters
    ----------
    stem_list
        Reference file stems to take cases from.
    scope
        Kind of test, used to select known discrepancies.
    outcomes
        Outcome codes to include; all by default.
    """
    params = []
    for stem in stem_list:
        ref = load(stem)
        for i, case in enumerate(ref.cases):
            if outcomes is not None and case["outcome"] not in outcomes:
                continue
            params.append(
                pytest.param(
                    (stem, i),
                    id=case_id(ref, i),
                    marks=known_discrepancy_marks(ref, i, scope),
                )
            )
    return params


def resolve(param: tuple[str, int]) -> tuple[ReferenceFile, int]:
    stem, i = param
    return load(stem), i


def row_params(stem_list: list[str], table: str) -> list:
    """``pytest.param((stem, row))`` for each row of a per-key table (``ei_keys``/``config_names``).

    Ids are made of the instrument, model version, configuration and (if present) incident
    energy.
    """
    params = []
    for stem in stem_list:
        ref = load(stem)
        for k, row in enumerate(ref[table]):
            if ref[table].dtype.names:
                configuration, e_init = str(row["configuration"]), row["e_init"]
                name = f"{ref.instrument}-{ref.model_version}-{configuration}-ei={_format_number(e_init)}"
            else:
                name = f"{ref.instrument}-{ref.model_version}-{row}"
            params.append(pytest.param((stem, k), id=name))
    return params
