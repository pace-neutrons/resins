"""Loading of committed reference data and construction of parametrized test cases.

The reference files in ``tests/reference_data`` are generated by ``dev/reference`` (see its
README). They define the test cases: tests are parametrized from the case table in each file,
so that the same cases are collected on every machine.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from functools import cache
from pathlib import Path
from typing import Callable

import numpy as np
import pytest

REFERENCE_DIR = Path(__file__).resolve().parents[1] / "reference_data"

OUTCOMES = ("value", "no_transmission", "rejected_ei", "rejected_frequency")
VALUE, NO_TRANSMISSION, REJECTED_EI, REJECTED_FREQUENCY = range(4)
EVALUATED = (VALUE, NO_TRANSMISSION)


@dataclass(frozen=True)
class ReferenceFile:
    """One loaded reference file."""

    stem: str  # e.g. "pychop/MARI_PyChop_fit_v1"
    arrays: dict[str, np.ndarray] = field(repr=False)
    metadata: dict = field(repr=False)

    @property
    def cases(self) -> np.ndarray:
        return self.arrays["cases"]

    def __getitem__(self, name: str) -> np.ndarray:
        return self.arrays[name]

    @property
    def instrument(self) -> str:
        return self.metadata["instrument"]

    @property
    def model_version(self) -> str:
        return self.metadata["model_version"]

    @property
    def frequency_settings(self) -> list[str]:
        """Setting names of the chopper frequencies, in column order (PyChop files)."""
        return self.metadata["frequency_settings"]

    def frequencies(self, i: int) -> list[float]:
        """The chopper frequencies of case ``i``: ``f0``, ``f1`` where defined."""
        case = self.cases[i]
        names = [n for n in ("f0", "f1") if n in case.dtype.names]
        return [float(case[n]) for n in names if not np.isnan(case[n])]

    def frequency_kwargs(self, i: int) -> dict[str, float]:
        return dict(zip(self.frequency_settings, self.frequencies(i)))


@cache
def load(stem: str) -> ReferenceFile:
    """Load ``reference_data/<stem>.npz`` (cached for the session)."""
    with np.load(REFERENCE_DIR / f"{stem}.npz", allow_pickle=False) as data:
        arrays = {k: data[k] for k in data.files if k != "metadata"}
        metadata = json.loads(str(data["metadata"]))
    return ReferenceFile(stem, arrays, metadata)


def stems(directory: str) -> list[str]:
    """All reference file stems in a sub-directory, sorted."""
    return sorted(f"{directory}/{p.stem}" for p in (REFERENCE_DIR / directory).glob("*.npz"))


def pychop_stems() -> list[str]:
    return stems("pychop")


